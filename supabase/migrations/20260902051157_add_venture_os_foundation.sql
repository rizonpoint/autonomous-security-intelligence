create function public.reserve_model_budget(
  p_budget_id uuid,
  p_routing_decision_id uuid,
  p_estimated_cost_usd numeric,
  p_ttl_seconds integer default 900
)
returns public.model_budget_reservations
language plpgsql
security invoker
set search_path = ''
as $$
declare
  selected_budget public.budgets;
  existing_reservation public.model_budget_reservations;
  created_reservation public.model_budget_reservations;
begin
  if p_estimated_cost_usd < 0 then
    raise exception 'estimated model cost must be non-negative';
  end if;
  if p_ttl_seconds < 30 or p_ttl_seconds > 3600 then
    raise exception 'reservation TTL must be between 30 and 3600 seconds';
  end if;

  select * into existing_reservation
  from public.model_budget_reservations
  where routing_decision_id = p_routing_decision_id;
  if found then
    return existing_reservation;
  end if;

  select * into selected_budget
  from public.budgets
  where id = p_budget_id
    and period_start <= now()
    and period_end > now()
  for update;

  if not found then
    raise exception 'active budget does not exist';
  end if;
  if not exists (
    select 1
    from public.model_routing_decisions rd
    join public.workspaces w on w.id = rd.workspace_id
    where rd.id = p_routing_decision_id
      and (
        selected_budget.scope_type = 'global'
        or (
          selected_budget.scope_type = 'venture'
          and w.venture_id = selected_budget.venture_id
        )
        or (
          selected_budget.scope_type not in ('global', 'venture')
          and rd.workspace_id = selected_budget.workspace_id
        )
      )
  ) then
    raise exception 'budget scope does not cover the routing decision';
  end if;
  if selected_budget.spent_usd + selected_budget.reserved_usd
       + p_estimated_cost_usd > selected_budget.hard_limit_usd then
    raise exception 'budget hard limit would be exceeded';
  end if;

  insert into public.model_budget_reservations (
    budget_id, routing_decision_id, estimated_cost_usd, expires_at
  ) values (
    p_budget_id, p_routing_decision_id, p_estimated_cost_usd,
    now() + make_interval(secs => p_ttl_seconds)
  ) returning * into created_reservation;

  update public.budgets
  set reserved_usd = reserved_usd + p_estimated_cost_usd,
      updated_at = now()
  where id = p_budget_id;

  return created_reservation;
end;
$$;

create function public.settle_model_budget(
  p_reservation_id uuid,
  p_actual_cost_usd numeric
)
returns public.model_budget_reservations
language plpgsql
security invoker
set search_path = ''
as $$
declare
  reservation public.model_budget_reservations;
  selected_budget public.budgets;
  final_status text;
begin
  if p_actual_cost_usd < 0 then
    raise exception 'actual model cost must be non-negative';
  end if;

  select * into reservation
  from public.model_budget_reservations
  where id = p_reservation_id
  for update;
  if not found or reservation.status <> 'reserved' then
    raise exception 'active model budget reservation does not exist';
  end if;

  select * into selected_budget
  from public.budgets
  where id = reservation.budget_id
  for update;

  final_status := case
    when selected_budget.spent_usd + p_actual_cost_usd
           > selected_budget.hard_limit_usd then 'over_limit'
    else 'settled'
  end;

  update public.budgets
  set reserved_usd = greatest(0, reserved_usd - reservation.estimated_cost_usd),
      spent_usd = spent_usd + p_actual_cost_usd,
      updated_at = now()
  where id = selected_budget.id;

  update public.model_budget_reservations
  set actual_cost_usd = p_actual_cost_usd,
      status = final_status,
      settled_at = now()
  where id = p_reservation_id
  returning * into reservation;

  return reservation;
end;
$$;

create function public.release_expired_model_budget_reservations()
returns integer
language plpgsql
security invoker
set search_path = ''
as $$
declare
  reservation public.model_budget_reservations;
  released integer := 0;
begin
  for reservation in
    select * from public.model_budget_reservations
    where status = 'reserved' and expires_at <= now()
    for update skip locked
  loop
    update public.budgets
    set reserved_usd = greatest(0, reserved_usd - reservation.estimated_cost_usd),
        updated_at = now()
    where id = reservation.budget_id;

    update public.model_budget_reservations
    set status = 'released', settled_at = now()
    where id = reservation.id;
    released := released + 1;
  end loop;
  return released;
end;
$$;

