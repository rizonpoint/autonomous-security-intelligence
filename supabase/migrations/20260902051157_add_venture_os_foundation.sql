-- v0.4 adds a venture layer between tenant organizations and operational
-- workspaces. It is additive so active v0.3 agents and work leases continue to
-- use their existing immutable workspace identities.

create table public.ventures (
  id uuid primary key default gen_random_uuid(),
  organization_id uuid not null
    references public.organizations(id) on delete cascade,
  slug text not null
    check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  name text not null check (length(trim(name)) between 1 and 160),
  venture_type text not null default 'operating'
    check (venture_type in ('operating', 'client', 'proof_of_concept', 'sandbox')),
  stage text not null default 'validation'
    check (stage in ('idea', 'validation', 'launch', 'operating', 'scaling', 'paused', 'archived')),
  thesis text,
  business_model text,
  status text not null default 'active'
    check (status in ('active', 'paused', 'archived')),
  metadata jsonb not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (organization_id, slug),
  unique (organization_id, id)
);

