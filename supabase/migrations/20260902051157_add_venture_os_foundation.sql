create or replace function control_plane_private.validate_workspace_venture()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if new.venture_id is not null and not exists (
    select 1 from public.ventures v
    where v.id = new.venture_id
      and v.organization_id = new.organization_id
      and v.status <> 'archived'
  ) then
    raise exception 'workspace venture must belong to the same active tenant';
  end if;
  return new;
end;
$$;

create trigger workspaces_validate_venture
before insert or update of venture_id, organization_id on public.workspaces
for each row execute function control_plane_private.validate_workspace_venture();

-- Existing business workspaces become root workspaces for derived ventures.
-- IDs are generated by Postgres and resolved by tenant/slug, never hard-coded.
insert into public.ventures (
  organization_id, slug, name, venture_type, stage, thesis, metadata
)
select
  w.organization_id,
  w.slug,
  w.name,
  'operating',
  'validation',
  w.purpose,
  jsonb_build_object(
    'migrated_from_workspace_id', w.id,
    'migration', 'v0.4'
  )
from public.workspaces w
where w.kind = 'business'
on conflict (organization_id, slug) do nothing;

update public.workspaces w
set venture_id = v.id
from public.ventures v
where w.kind = 'business'
  and v.organization_id = w.organization_id
  and v.slug = w.slug
  and w.venture_id is null;

