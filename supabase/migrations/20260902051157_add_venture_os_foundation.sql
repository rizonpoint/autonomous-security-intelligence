create or replace function control_plane_private.validate_agent_membership()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  home_organization_id uuid;
  target_organization_id uuid;
begin
  select w.organization_id into home_organization_id
  from public.agents a
  join public.workspaces w on w.id = a.workspace_id
  where a.id = new.agent_id;

  select w.organization_id into target_organization_id
  from public.workspaces w
  where w.id = new.workspace_id;

  if home_organization_id is null
     or target_organization_id is null
     or home_organization_id <> target_organization_id then
    raise exception 'agent memberships cannot cross tenant organizations';
  end if;
  return new;
end;
$$;

