create or replace function control_plane_private.validate_model_routing_decision()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  workspace_organization_id uuid;
  profile_organization_id uuid;
  policy_profile_id uuid;
  deployment_organization_id uuid;
begin
  select organization_id into workspace_organization_id
  from public.workspaces where id = new.workspace_id;
  select organization_id into profile_organization_id
  from public.task_profiles where id = new.task_profile_id;
  select task_profile_id into policy_profile_id
  from public.model_routing_policies where id = new.routing_policy_id;
  select organization_id into deployment_organization_id
  from public.model_deployments where id = new.selected_model_deployment_id;

  if workspace_organization_id is null
     or profile_organization_id <> workspace_organization_id then
    raise exception 'routing task profile must belong to the workspace tenant';
  end if;
  if policy_profile_id is distinct from new.task_profile_id then
    raise exception 'routing policy does not belong to the selected task profile';
  end if;
  if deployment_organization_id is not null
     and deployment_organization_id <> workspace_organization_id then
    raise exception 'model deployment is not available to the workspace tenant';
  end if;
  return new;
end;
$$;

